CREATE TABLE IF NOT EXISTS lectores (
Id INTEGER PRIMARY KEY AUTOINCREMENT,
CODIGO TEXT NOT NULL,
NOMBRE TEXT NOT NULL,
CORREO TEXT NOT NULL,
TELEFONO TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS LIBROS (
Id INTEGER PRIMARY KEY AUTOINCREMENT,
CODIGO TEXT NOT NULL,
TITULO TEXT NOT NULL,
AUTOR INTEGER,
EJEMPLARES INTEGER NOT NULL
CHECK (EJEMPLARES>=0));


CREATE TABLE IF NOT EXISTS AUTOR (
Id INTEGER PRIMARY KEY AUTOINCREMENT,
NOMBRE TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS PRESTAMO (
Id INTEGER PRIMARY KEY AUTOINCREMENT,
LECTORID  INTEGER NOT NULL,
LIBRO ID INTEGER NOT NULL,
FECHAPRESTAMO TEXT NOT NULL    //registra DD/MM/YY
FECHADEVOLUCION TEXT NOT NULL,
FECHALIMITE TEXT NOT NULL,
CHECK (DATE(FECHALIMITE))>= 
DATE(FECHAPRESTAMO))
FOREIGN KEY (LECTORID) REFERENCES
LECTORI(ID) ON DELETE CASCARE);

CREATE INDEX IF NOT EXISTS IDX PRESTAMO LECTORID
ON PRESTAMO (LECTORID);